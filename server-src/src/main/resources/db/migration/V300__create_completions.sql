-- completion 도메인 소유: completions(도착 인증 기록). H2(PostgreSQL 모드)와 PostgreSQL 17 공용 DDL.
-- completion_date는 한국 시간(Asia/Seoul, Clock 기준) 날짜이고, 같은 장소 하루 1회 규칙을 유니크 제약으로 강제한다.
-- 위반(연타, 동시 요청)은 서비스가 COMPLETION409로 변환한다.
-- photo_key, photo_uploaded_at은 사진 업로드(쟁점 8 대기) 때 쓸 자리이며 지금은 항상 NULL이다.
CREATE TABLE completions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id           BIGINT           NOT NULL,
    place_id          BIGINT           NOT NULL,
    completion_date   DATE             NOT NULL,
    completed_at      TIMESTAMP        NOT NULL,
    first_visit       BOOLEAN          NOT NULL,
    earned_point      INT              NOT NULL,
    lat               DOUBLE PRECISION NOT NULL,
    lng               DOUBLE PRECISION NOT NULL,
    accuracy_m        DOUBLE PRECISION NOT NULL,
    photo_key         VARCHAR(255)     NULL,
    photo_uploaded_at TIMESTAMP        NULL,
    CONSTRAINT pk_completions PRIMARY KEY (id),
    CONSTRAINT uk_completions_user_place_date UNIQUE (user_id, place_id, completion_date),
    CONSTRAINT fk_completions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_completions_place FOREIGN KEY (place_id) REFERENCES places (id)
);

-- 활동 일지 커서 조회(user_id = ? AND id < ? ORDER BY id DESC)
CREATE INDEX idx_completions_user_id_id ON completions (user_id, id);
-- 활동 일지 기간 필터
CREATE INDEX idx_completions_user_completed_at ON completions (user_id, completed_at);
-- 장소별 인증 횟수, 최근 N일 인기 집계
CREATE INDEX idx_completions_place_completed_at ON completions (place_id, completed_at);
