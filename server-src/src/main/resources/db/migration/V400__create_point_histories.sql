-- point 도메인 소유: point_histories(포인트 적립 내역, 누적 포인트의 원천). 포인트는 쌓기만 한다(음수 없음).
-- earned_at(적립 시각)이 일/주 집계의 기준이다(Gray Area A4). 한 completion당 type별 1건.
CREATE TABLE point_histories (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id       BIGINT      NOT NULL,
    completion_id BIGINT      NOT NULL,
    place_id      BIGINT      NOT NULL,
    type          VARCHAR(20) NOT NULL,
    point         INT         NOT NULL,
    earned_at     TIMESTAMP   NOT NULL,
    CONSTRAINT pk_point_histories PRIMARY KEY (id),
    CONSTRAINT uk_point_histories_completion_type UNIQUE (completion_id, type),
    CONSTRAINT fk_point_histories_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_point_histories_completion FOREIGN KEY (completion_id) REFERENCES completions (id),
    CONSTRAINT fk_point_histories_place FOREIGN KEY (place_id) REFERENCES places (id),
    CONSTRAINT ck_point_histories_point CHECK (point >= 0)
);

-- 적립 내역 커서 조회(user_id = ? AND id < ? ORDER BY id DESC)와 누적 합계
CREATE INDEX idx_point_histories_user_id_id ON point_histories (user_id, id);
-- 오늘 획득 포인트, 사용자별 기간 집계
CREATE INDEX idx_point_histories_user_earned_at ON point_histories (user_id, earned_at);
-- 기간별 랭킹/통계(3단계)
CREATE INDEX idx_point_histories_earned_at_user ON point_histories (earned_at, user_id);
