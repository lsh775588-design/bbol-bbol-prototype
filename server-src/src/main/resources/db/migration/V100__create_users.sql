-- user 도메인 소유: users. H2(PostgreSQL 모드)와 PostgreSQL 17 공용 DDL.
-- status(ACTIVE, WITHDRAWN) + withdrawn_at으로 탈퇴를 표현한다. 이메일/닉네임은 탈퇴 시 NULL로 비워 재사용할 수 있다.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email VARCHAR(255) NULL,
    password_hash VARCHAR(100) NULL,
    login_type VARCHAR(20) NOT NULL,
    kakao_id VARCHAR(64) NULL,
    nickname VARCHAR(30) NULL,
    nickname_changed_at TIMESTAMP NULL,
    status VARCHAR(20) NOT NULL,
    onboarding_completed BOOLEAN NOT NULL DEFAULT FALSE,
    withdrawn_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_nickname UNIQUE (nickname),
    CONSTRAINT uk_users_kakao_id UNIQUE (kakao_id)
);
