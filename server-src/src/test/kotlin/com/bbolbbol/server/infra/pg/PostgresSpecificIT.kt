package com.bbolbbol.server.infra.pg

import com.bbolbbol.server.domain.completion.service.CompletionService
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.DisplayName
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable
import org.springframework.jdbc.support.SQLErrorCodeSQLExceptionTranslator
import java.sql.Connection
import java.sql.DriverManager
import java.sql.SQLException

/**
 * 실제 PostgreSQL에서만 확인할 수 있는 동작(opt-in). 환경변수 BBOL_IT_PG=true일 때만 돈다.
 * 접속: BBOL_IT_PG_URL(예: jdbc:postgresql://localhost:5432/bbol_test), BBOL_IT_PG_USER, BBOL_IT_PG_PASSWORD.
 * 임시 테이블(TEMP)만 만들고 연결을 닫으면 사라지므로 어떤 스키마에도 흔적이 남지 않는다.
 */
@EnabledIfEnvironmentVariable(named = "BBOL_IT_PG", matches = "true")
class PostgresSpecificIT {

	private fun <T> withConn(block: (Connection) -> T): T =
		DriverManager.getConnection(
			System.getenv("BBOL_IT_PG_URL") ?: "jdbc:postgresql://localhost:5432/bbol_test",
			System.getenv("BBOL_IT_PG_USER"),
			System.getenv("BBOL_IT_PG_PASSWORD"),
		).use(block)

	@Test
	@DisplayName("실제 PostgreSQL의 유니크 위반 예외를 Spring이 변환한 뒤에도 제약 이름으로 중복을 식별한다")
	fun realUniqueViolationIsDetectedByConstraintName() {
		withConn { c ->
			c.createStatement().use {
				it.execute(
					"create temp table t_completions (user_id bigint, place_id bigint, completion_date date, " +
						"constraint uk_completions_user_place_date unique (user_id, place_id, completion_date))",
				)
				it.execute("insert into t_completions values (1, 1, date '2026-11-14')")
			}
			val ex = try {
				c.createStatement().use { it.execute("insert into t_completions values (1, 1, date '2026-11-14')") }
				error("유니크 위반이 나야 한다")
			} catch (e: SQLException) {
				e
			}
			assertThat(ex.sqlState).describedAs("PostgreSQL의 unique_violation SQLSTATE").isEqualTo("23505")
			assertThat(ex.message).contains("duplicate key value violates unique constraint \"uk_completions_user_place_date\"")
			val translated = SQLErrorCodeSQLExceptionTranslator().translate("insert", "insert into t", ex)!!
			assertThat(translated).isInstanceOf(org.springframework.dao.DataIntegrityViolationException::class.java)
			assertThat(CompletionService.isDuplicateCompletion(translated)).isTrue()
		}
	}

	@Test
	@DisplayName("NULL이 들어간 유니크 컬럼(email, nickname, kakao_id, photo_key 모양)은 NULL 여러 행을 허용하고 값은 하나만 허용한다")
	fun nullableUniqueAllowsManyNulls() {
		withConn { c ->
			c.createStatement().use {
				it.execute("create temp table t_u (id serial primary key, email text, constraint uk_t_u_email unique (email))")
				it.execute("insert into t_u(email) values (null), (null), (null)")
				it.execute("insert into t_u(email) values ('a@b.c')")
			}
			val dup = try {
				c.createStatement().use { it.execute("insert into t_u(email) values ('a@b.c')") }
				false
			} catch (e: SQLException) {
				e.sqlState == "23505"
			}
			assertThat(dup).isTrue()
		}
	}

	@Test
	@DisplayName("coalesce(sum(int),0)는 bigint로, count는 bigint로 돌아온다(JDBC getObject 타입)")
	fun aggregateTypes() {
		withConn { c ->
			c.createStatement().use {
				it.execute("create temp table t_p (earned int)")
				it.execute("insert into t_p values (300), (50)")
				val rs = it.executeQuery(
					"select coalesce(sum(earned), 0) s, count(*) n, coalesce(sum(case when earned > 100 then 1 else 0 end), 0) b from t_p",
				)
				rs.next()
				assertThat(rs.getObject("s")).isInstanceOf(java.lang.Long::class.java)
				assertThat(rs.getObject("n")).isInstanceOf(java.lang.Long::class.java)
				assertThat(rs.getObject("b")).describedAs("sum(int)는 bigint").isInstanceOf(java.lang.Long::class.java)
				val empty = it.executeQuery("select coalesce(sum(earned), 0) s from t_p where earned > 1000")
				empty.next()
				assertThat(empty.getLong("s")).isEqualTo(0L)
			}
		}
	}

	@Test
	@DisplayName("시퀀스는 유니크 위반으로 실패한 INSERT에서도 값을 소모한다(id에 구멍이 생기는 것이 정상)")
	fun identityGapsAfterFailedInsert() {
		withConn { c ->
			c.createStatement().use {
				it.execute("create temp table t_g (id bigint generated by default as identity primary key, k int unique)")
				it.execute("insert into t_g(k) values (1)")
				try { it.execute("insert into t_g(k) values (1)") } catch (_: SQLException) {}
				it.execute("insert into t_g(k) values (2)")
				val rs = it.executeQuery("select max(id) from t_g")
				rs.next()
				assertThat(rs.getLong(1)).describedAs("실패한 INSERT가 id 2를 소모해서 마지막 id는 3").isEqualTo(3L)
			}
		}
	}
}
